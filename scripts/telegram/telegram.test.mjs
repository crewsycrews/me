test("page polling requires exact generated bytes; an old 200 page is insufficient", async () => {
  let calls = 0, sleeps = 0;
  const p = await post();
  await waitForPage(p, hash("new html"), {
    fetcher: async () => new Response(++calls === 1 ? "old html" : "new html"),
    sleep: async () => { sleeps++; }, attempts: 2,
  });
  assert.equal(calls, 2);
  assert.equal(sleeps, 1);
  await assert.rejects(waitForPage(p, hash("new html"), {
    fetcher: async () => new Response("old html"), attempts: 1,
  }), /не отправлен/);
});

