test("API handles rejection, ambiguous errors, and unchanged edits without exposing token", async () => {
  const json = (value, status = 200) => new Response(JSON.stringify(value), { status });
  await assert.rejects(telegramRequest("sendMessage", {}, "secret", async () => json({ ok: false, error_code: 403 }, 403)), (e) => e.rejected === true);
  await assert.rejects(telegramRequest("sendMessage", {}, "secret", async () => { throw new Error("https://api.telegram.org/botsecret/sendMessage"); }), (e) => !e.message.includes("secret") && !e.rejected);
  await assert.rejects(telegramRequest("sendMessage", {}, "secret", async () => json({ ok: false, error_code: 500 }, 500)), (e) => !e.rejected);
  assert.equal((await telegramRequest("editMessageText", { message_id: 34 }, "secret", async () => json({ ok: false, error_code: 400, description: "Bad Request: message is not modified" }, 400))).message_id, 34);
});

