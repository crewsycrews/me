async function post(markdown = "Текст **заметки**.", telegram = { publish: true, mode: "full" }) {
  const parsed = await parseMarkdown(markdown, { highlight: false });
  return { ...parsed, data: { ...parsed.data, title: "Заметка 👋" }, slug: "2026-09-10-example", url: "https://example.com/blog/2026-09-10-example", telegram };
}

function memoryStore() {
  let durable = { version: 1, channel, posts: {} };
  return {
    state: structuredClone(durable),
    async save(next) { durable = structuredClone(validateState(next)); },
    reload() { this.state = structuredClone(durable); return this; },
  };
}

test("Markdown preserves Cyrillic, emoji offsets, links, code, lists and image URLs", async () => {
  const payload = await makeMessage(await post("👋 **жирный & <текст>** [ссылка](/about)\n\n`x < y`\n\n```js\nconst x = 1;\n```\n\n1. Один\n2. Два\n\n![Фото](/photo.png)"));
  const bold = payload.entities.find((e) => e.type === "bold" && e.offset > 0);
  assert.equal(payload.text.slice(bold.offset, bold.offset + bold.length), "жирный & <текст>");
  assert.ok(payload.entities.some((e) => e.url === "https://example.com/about"));
  assert.ok(payload.entities.some((e) => e.url === "https://example.com/photo.png"));
  assert.ok(payload.entities.some((e) => e.type === "pre" && e.language === "js"));
  assert.ok(payload.entities.some((e) => e.type === "code"));
  assert.match(payload.text, /1\. Один\n2\. Два/);
  assert.match(payload.text, /Читать в блоге: https:/);
  for (const entity of payload.entities) assert.ok(entity.offset + entity.length <= payload.text.length);
});

