  await fresh.save(fresh.state);
  await assert.rejects(a.save(a.state), /Git push/);
  assert.equal(openGitState(join(root, "a")).state.posts.example.messageId, 123);
  assert.equal(git(join(root, "a"), "status", "--short"), "?? dirty.txt");
  assert.equal(git(join(root, "remote.git"), "ls-tree", "--name-only", "telegram-state"), "state.json");
